import fs from 'node:fs/promises'
import path from 'node:path'
import { pathToFileURL } from 'node:url'

const root = process.cwd()
const distDir = path.join(root, 'dist')
const releaseDir = path.join(root, 'release')
const hostedDir = path.join(releaseDir, 'hosted')
const offlineDir = path.join(releaseDir, 'offline')

export async function copyDirectoryRecursive(source, destination) {
  await fs.mkdir(destination, { recursive: true })
  const entries = await fs.readdir(source, { withFileTypes: true })

  for (const entry of entries) {
    const from = path.join(source, entry.name)
    const to = path.join(destination, entry.name)

    if (entry.isDirectory()) {
      await copyDirectoryRecursive(from, to)
    } else {
      await fs.copyFile(from, to)
    }
  }
}

export async function resetReleaseDirectory() {
  await fs.rm(releaseDir, { recursive: true, force: true })
  await fs.mkdir(hostedDir, { recursive: true })
  await fs.mkdir(offlineDir, { recursive: true })
}

export function buildReleaseNotes() {
  return [
    '# Airlock Release Artifacts',
    '',
    '## hosted/',
    '- Standard Vite output for hosted deployment.',
    '',
    '## offline/',
    '- offline.html: self-contained single-file shell artifact.',
    '- assets/: copied runtime assets used by advanced flows.',
    '',
    'Generated by scripts/release-artifacts.mjs',
  ].join('\n')
}

export async function writeReleaseNotes() {
  await fs.writeFile(path.join(releaseDir, 'README.txt'), buildReleaseNotes(), 'utf8')
}

export async function run() {
  await resetReleaseDirectory()

  await copyDirectoryRecursive(distDir, hostedDir)

  await fs.copyFile(path.join(distDir, 'offline.html'), path.join(offlineDir, 'airlock-offline.html'))
  await copyDirectoryRecursive(path.join(distDir, 'assets'), path.join(offlineDir, 'assets'))

  await writeReleaseNotes()

  console.log(`Release artifacts created in: ${releaseDir}`)
}

const isDirectRun = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href

if (isDirectRun) {
  run().catch((error) => {
    console.error('Failed creating release artifacts.')
    console.error(error)
    process.exitCode = 1
  })
}
